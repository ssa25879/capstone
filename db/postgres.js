// Postgres(Supabase) 데이터베이스 모듈
// SQLite 모듈(sqlite.js)과 같은 함수 이름·반환 형식을 제공한다.
const fs = require("fs");
const { Pool } = require("pg");
const { hashPassword, verifyPassword } = require("./password");

// SSL 설정
// - 기본: 서버 인증서를 검증한다. Supabase 대시보드에서 받은 CA 인증서를
//   DATABASE_CA_CERT(PEM 내용 또는 파일 경로)로 지정해야 한다.
// - DATABASE_SSL=disable: SSL 미사용 (로컬 테스트용)
// - DATABASE_SSL=no-verify: 암호화만 하고 인증서는 검증하지 않음 (CA 인증서를 쓸 수 없을 때만)
function sslConfig() {
    if (process.env.DATABASE_SSL === "disable") {
        return false;
    }
    if (process.env.DATABASE_SSL === "no-verify") {
        console.warn("경고: DB 서버 인증서를 검증하지 않습니다. 가능하면 DATABASE_CA_CERT를 지정하세요.");
        return { rejectUnauthorized: false };
    }
    const ca = process.env.DATABASE_CA_CERT;
    if (!ca) {
        throw new Error("DATABASE_CA_CERT가 필요합니다. Supabase 대시보드에서 SSL 인증서를 받아 지정하세요.");
    }
    return { ca: ca.includes("BEGIN CERTIFICATE") ? ca : fs.readFileSync(ca, "utf8"), rejectUnauthorized: true };
}

// 연결 문자열의 sslmode가 위 SSL 설정을 덮어쓰지 않도록 제거
const url = new URL(process.env.DATABASE_URL);
url.searchParams.delete("sslmode");

const pool = new Pool({
    connectionString: url.toString(),
    ssl: sslConfig(),
    max: Number(process.env.PG_POOL_MAX) || 5,
});

const query = async (text, params) => (await pool.query(text, params)).rows;

// 화면 표시용 시간 (한국 시간, 분 단위)
const KST = (col) => `to_char(${col} AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD HH24:MI')`;

// 테이블 생성. Supabase는 public 스키마를 REST API로 노출하므로 RLS를 켜서
// anon/authenticated 키로는 접근할 수 없게 한다. (서버는 테이블 소유자로 접속해 RLS 영향 없음)
async function init() {
    await pool.query(`
        CREATE TABLE IF NOT EXISTS users (
            user_id       TEXT PRIMARY KEY,
            password_hash TEXT NOT NULL,
            user_name     TEXT NOT NULL,
            bio           TEXT,
            student_id    TEXT,
            ip_address    TEXT,
            browser_info  TEXT,
            created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
        );

        CREATE TABLE IF NOT EXISTS posts (
            post_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id    TEXT NOT NULL REFERENCES users(user_id),
            content    TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );

        CREATE TABLE IF NOT EXISTS comments (
            comment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            post_id    INTEGER NOT NULL REFERENCES posts(post_id),
            user_id    TEXT NOT NULL REFERENCES users(user_id),
            content    TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );

        CREATE TABLE IF NOT EXISTS follows (
            follower_id  TEXT NOT NULL REFERENCES users(user_id),
            following_id TEXT NOT NULL REFERENCES users(user_id),
            PRIMARY KEY (follower_id, following_id)
        );

        CREATE TABLE IF NOT EXISTS reports (
            user_id    TEXT NOT NULL REFERENCES users(user_id),
            post_id    INTEGER NOT NULL REFERENCES posts(post_id),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            PRIMARY KEY (user_id, post_id)
        );

        CREATE TABLE IF NOT EXISTS chat_messages (
            message_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            room_id         TEXT NOT NULL,
            user_id         TEXT NOT NULL REFERENCES users(user_id),
            message_content TEXT NOT NULL,
            message_time    TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE INDEX IF NOT EXISTS idx_chat_room ON chat_messages(room_id);

        ALTER TABLE users         ENABLE ROW LEVEL SECURITY;
        ALTER TABLE posts         ENABLE ROW LEVEL SECURITY;
        ALTER TABLE comments      ENABLE ROW LEVEL SECURITY;
        ALTER TABLE follows       ENABLE ROW LEVEL SECURITY;
        ALTER TABLE reports       ENABLE ROW LEVEL SECURITY;
        ALTER TABLE chat_messages ENABLE ROW LEVEL SECURITY;
    `);
}

async function CountUsers() {
    const [row] = await query("SELECT COUNT(*)::int AS n FROM users");
    return row.n;
}

async function RegisterUser({ userid, password, user_name, bio, student_id, ipAddress, browser }) {
    const result = await pool.query(`
        INSERT INTO users (user_id, password_hash, user_name, bio, student_id, ip_address, browser_info)
        VALUES ($1, $2, $3, $4, $5, $6, $7)
        ON CONFLICT (user_id) DO NOTHING
    `, [userid, hashPassword(password), user_name, bio || "", student_id || "", ipAddress || "", browser || ""]);
    if (result.rowCount === 0) {
        return { registerSuccess: false, errorMessage: "이미 사용 중인 아이디입니다." };
    }
    return { registerSuccess: true, errorMessage: null };
}

async function LoginUser(userid, password) {
    const [user] = await query("SELECT user_id, user_name, bio, password_hash FROM users WHERE user_id = $1", [userid]);
    if (!user || !verifyPassword(password, user.password_hash)) {
        return undefined;
    }
    return { user_id: user.user_id, user_name: user.user_name, bio: user.bio };
}

async function GetUserInfo(userid) {
    const [user] = await query("SELECT user_id, user_name, bio FROM users WHERE user_id = $1", [userid]);
    return user;
}

async function CreatePost(userId, content) {
    await query("INSERT INTO posts (user_id, content) VALUES ($1, $2)", [userId, content]);
    return "게시글이 작성되었습니다.";
}

async function GetPost({ count, follow, userId }) {
    let where = "";
    if (follow && userId) {
        where = `WHERE p.user_id = $1
                    OR p.user_id IN (SELECT following_id FROM follows WHERE follower_id = $1)`;
    }
    return query(`
        SELECT p.post_id, p.user_id, u.user_name, p.content,
               ${KST("p.created_at")} AS created_at,
               CASE WHEN f.follower_id IS NULL THEN 'N' ELSE 'Y' END AS following
        FROM posts p
        JOIN users u ON u.user_id = p.user_id
        LEFT JOIN follows f ON f.following_id = p.user_id AND f.follower_id = $1
        ${where}
        ORDER BY p.post_id DESC
        LIMIT $2
    `, [userId || "", count]);
}

async function GetComment(postId) {
    // 클라이언트(main.js)가 대문자 컬럼명을 사용한다
    return query(`
        SELECT user_id AS "USER_ID", content AS "CONTENT"
        FROM comments WHERE post_id = $1 ORDER BY comment_id
    `, [postId]);
}

async function CreateComment(postId, userId, content) {
    await query("INSERT INTO comments (post_id, user_id, content) VALUES ($1, $2, $3)", [postId, userId, content]);
}

// 팔로우 상태를 토글한다
async function FollowUser(followerId, followingId) {
    const removed = await pool.query("DELETE FROM follows WHERE follower_id = $1 AND following_id = $2", [followerId, followingId]);
    if (removed.rowCount === 0) {
        await query("INSERT INTO follows (follower_id, following_id) VALUES ($1, $2) ON CONFLICT DO NOTHING", [followerId, followingId]);
    }
}

async function Report(userId, postId) {
    await query("INSERT INTO reports (user_id, post_id) VALUES ($1, $2) ON CONFLICT DO NOTHING", [userId, postId]);
}

async function InsertChatMessage(roomId, userId, content) {
    await query("INSERT INTO chat_messages (room_id, user_id, message_content) VALUES ($1, $2, $3)", [roomId, userId, content]);
}

async function GetChatMessages(roomId) {
    return query(`
        SELECT user_id, message_content, ${KST("message_time")} AS message_time
        FROM chat_messages WHERE room_id = $1 ORDER BY message_id
    `, [roomId]);
}

// 사용자가 참여한 대화방별 마지막 메시지 (방 ID는 "아이디1@아이디2" 형식)
async function GetChatList(userId) {
    const rows = await query(`
        SELECT * FROM (
            SELECT DISTINCT ON (room_id) room_id, message_id, message_content,
                   ${KST("message_time")} AS message_time
            FROM chat_messages
            WHERE split_part(room_id, '@', 1) = $1 OR split_part(room_id, '@', 2) = $1
            ORDER BY room_id, message_id DESC
        ) latest
        ORDER BY message_id DESC
    `, [userId]);
    return rows.map((row) => {
        const [a, b] = row.room_id.split("@");
        return { user_id: a === userId ? b : a, message_content: row.message_content, message_time: row.message_time };
    });
}

module.exports = {
    init,
    close: () => pool.end(),
    CountUsers,
    RegisterUser,
    LoginUser,
    GetUserInfo,
    CreatePost,
    GetPost,
    GetComment,
    CreateComment,
    FollowUser,
    Report,
    InsertChatMessage,
    GetChatMessages,
    GetChatList,
};
